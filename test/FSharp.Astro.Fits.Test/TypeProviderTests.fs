type LenientObs = FitsProvider<Sample, Lenient=true>

[<Fact>]
let ``lenient providers open non-conforming files`` () =
    use original = Fits.openFile Sample
    let bytes = Fits.toBytes [ Fits.copy original 0 ]
    let unpadded =
        Array.sub bytes 0 (int original.Primary.DataOffset + int original.Primary.DataLength)
    use file = LenientObs.Parse unpadded
    Assert.Equal("M31", file.Primary.OBJECT)
    Assert.Throws<FitsException>(fun () -> Obs.Parse unpadded |> ignore) |> ignore

/// The unit of a flux density per unit wavelength, which TUNIT3 of the units fixture spells in the
/// IAU style as "erg s-1 cm-2 Angstrom-1".
[<Measure>]
type flam = erg / (s cm^2 angstrom)

type Measured = FitsProvider<"fixtures/units.txt", ResolutionFolder=__SOURCE_DIRECTORY__>

/// A file shaped like the units fixture.
let measured =
    Fits.toBytes [
        Fits.primary
            (Header.set "BUNIT" (CardValue.String "Jy") Header.empty)
            (Image.create [| 2; 2 |] (ImageData.Float32 [| 1.f; 2.f; 3.f; 4.f |]))
        Fits.binaryTable (Header.set "EXTNAME" (CardValue.String "UNITS") Header.empty) [
            Table.ofFloat64s "FLUX" [| 1500.0; 2500.0 |] |> Table.withUnit "mJy"
            Table.ofFloat32s "RA" [| 10.f; 20.f |] |> Table.withUnit "deg"
            Table.ofFloat32s "FLAM" [| 1.f; 2.f |]
            |> Table.withUnit "erg s-1 cm-2 Angstrom-1"
            Table.ofFloat32s "SB" [| 3.f; 4.f |] |> Table.withUnit "Jy/beam"
            Table.ofInt32s "NPIX" [| 5; 6 |] |> Table.withUnit "pixel"
        ]
    ]

[<Fact>]
let ``TUNIT gives a floating point column a unit of measure`` () =
    use file = Measured.Parse measured
    let units = file.UNITS
    Assert.Equal<float<mJy>[]>([| 1500.0<mJy>; 2500.0<mJy> |], units.FLUX)
    Assert.Equal<float32<deg>[]>([| 10.f<deg>; 20.f<deg> |], units.RA)
    Assert.Equal<float32<flam>[]>([| 1.f<flam>; 2.f<flam> |], units.FLAM)
    Assert.Equal(20.f<deg>, units.Rows[1].RA)

[<Fact>]
let ``a unit with no measure behind it leaves the column bare`` () =
    use file = Measured.Parse measured
    // Nothing here declares a measure for a beam.
    Assert.Equal<float32[]>([| 3.f; 4.f |], file.UNITS.SB)
    // An integer column keeps its unit in the documentation only.
    Assert.Equal<int[]>([| 5; 6 |], file.UNITS.NPIX)

[<Fact>]
let ``BUNIT gives the physical pixels a unit of measure`` () =
    use file = Measured.Parse measured
    Assert.Equal<float<Jy>[]>([| 1.0<Jy>; 2.0<Jy>; 3.0<Jy>; 4.0<Jy> |], file.Primary.Pixels)
    // Data is what is stored, before BZERO and BSCALE, so it carries no unit.
    Assert.Equal<float32[]>([| 1.f; 2.f; 3.f; 4.f |], file.Primary.Data)

type AsciiCat = FitsProvider<"fixtures/ascii.txt", ResolutionFolder=__SOURCE_DIRECTORY__>

/// A file shaped like the ASCII fixture.
let asciiBytes =
    Fits.toBytes [
        Fits.emptyPrimary Header.empty
        Fits.asciiTable (Header.set "EXTNAME" (CardValue.String "ACAT") Header.empty) [
            Ascii.ofStrings "NAME" 6 [| "alpha"; "beta" |]
            Ascii.ofInt64s "ID" 4 [| 1L; -22L |]
            Ascii.ofFloat64s "RA" 8 3 [| 10.5; 266.417 |] |> Ascii.withUnit "deg"
            Ascii.ofExponentials "FLUX" 11 4 [| 1.5; 2.0 |] |> Ascii.withUnit "mJy"
        ]
    ]

[<Fact>]
let ``an ASCII table gets typed rows and columns`` () =
    use file = AsciiCat.Parse asciiBytes
    let cat = file.ACAT
    Assert.Equal(2, cat.Count)
    Assert.Equal<string[]>([| "alpha"; "beta" |], cat.NAME)
    // An Iw field of any width decodes as int64.
    Assert.Equal<int64[]>([| 1L; -22L |], cat.ID)
    // The real forms decode as float, and TUNIT gives them their measure.
    Assert.Equal<float<deg>[]>([| 10.5<deg>; 266.417<deg> |], cat.RA)
    Assert.Equal<float<mJy>[]>([| 1.5<mJy>; 2.0<mJy> |], cat.FLUX)

[<Fact>]
let ``ASCII rows read one cell at a time`` () =
    use file = AsciiCat.Parse asciiBytes
    let cat = file.ACAT
    let row = cat.Rows[1]
    Assert.Equal(1, row.Index)
    Assert.Equal("beta", row.NAME)
    Assert.Equal(-22L, row.ID)
    Assert.Equal(266.417<deg>, row.RA)
    Assert.Equal(2.0<mJy>, row.FLUX)
    Assert.Equal("alpha", (cat.Row 0).NAME)

[<Fact>]
let ``the untyped ASCII table is reachable from the provided type`` () =
    use file = AsciiCat.Parse asciiBytes
    let table = file.ACAT.Table
    Assert.Equal(2, table.Rows)
    Assert.Equal(32, table.RowLength)
    Assert.Equal<int[]>([| 1; 8; 13; 22 |], table.Columns |> Array.map (fun c -> c.Start))
    Assert.Equal(HduKind.AsciiTable, file.ACAT.Info.Kind)
