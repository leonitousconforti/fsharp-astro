/// Serves one byte array at a local URL until disposed.
let serve (bytes: byte[]) : string * IDisposable =
    let listener = new HttpListener()

    let rec start (tries: int) : int =
        let port = Random.Shared.Next(20000, 60000)
        listener.Prefixes.Clear()
        listener.Prefixes.Add $"http://127.0.0.1:{port}/"

        try
            listener.Start()
            port
        with _ when tries > 0 ->
            start (tries - 1)

    let port = start 10

    let rec respond () = async {
        match! listener.GetContextAsync() |> Async.AwaitTask |> Async.Catch with
        | Choice1Of2 context ->
            context.Response.ContentLength64 <- int64 bytes.Length
            do!
                context.Response.OutputStream.WriteAsync(bytes, 0, bytes.Length)
                |> Async.AwaitTask
            context.Response.Close()
            return! respond ()
        | Choice2Of2 _ -> ()
    }

    Async.Start(respond ())

    $"http://127.0.0.1:{port}/sample.fits",
    {
        new IDisposable with
            member _.Dispose() =
                listener.Stop()
                listener.Close()
    }

[<Literal>]
let Fixtures = __SOURCE_DIRECTORY__ + "/fixtures"

[<Literal>]
let Sample = Fixtures + "/sample.fits"

type Obs = FitsProvider<Sample>

[<Fact>]
let ``keywords are typed properties`` () =
    use file = Obs.Load Sample
    let primary = file.Primary
    Assert.Equal("M31", primary.OBJECT)
    Assert.Equal(30.0, primary.EXPTIME)
    Assert.Equal("V", primary.FILTER)
    Assert.Equal("2026-10-05", primary.DATE_OBS)
    Assert.Equal(0.5, primary.ESO_DET_DIT)
    Assert.Equal(2L, primary.NAXIS)
    Assert.True primary.SIMPLE
    Assert.Equal<string list>([ "generated by fitsharp" ], primary.Comments)
    Assert.Equal(Some "M31", Header.tryString "OBJECT" primary.Header)
    Assert.Equal(0, primary.Info.Index)
    Assert.Equal(3, file.File.Count)

[<Fact>]
let ``images are typed by BITPIX`` () =
    use file = Obs.Load Sample
    Assert.Equal<int[]>([| 2; 3 |], file.Primary.Shape)
    Assert.Equal<float32[]>([| 1.f; 2.f; 3.f; 4.f; 5.f; 6.f |], file.Primary.Data)
    Assert.Equal<int16[]>([| -32768s; -32767s; 32767s; -32761s |], file.SCI.Data)
    Assert.Equal<float[]>([| 0.0; 1.0; 65535.0; 7.0 |], file.SCI.Pixels)
    Assert.Equal(BitPix.Int16, file.SCI.Image.Data.BitPix)

[<Fact>]
let ``tables have typed rows and columns`` () =
    use file = Obs.Load Sample
    let cat = file.CAT
    Assert.Equal(2, cat.Count)
    Assert.Equal<int[]>([| 1; 2 |], cat.ID)
    Assert.Equal<string[]>([| "alpha"; "beta" |], cat.NAME)
    // TUNIT3 is Jy, so the column comes out tagged.
    Assert.Equal<float32<Jy>[]>([| 1.5f<Jy>; 2.5f<Jy> |], cat.FLUX)
    Assert.Equal<float32[][]>([| [| 1.f; 2.f; 3.f |]; [| 4.f |] |], cat.SPEC)
    Assert.Equal<int16[]>([| 1s; 2s; 3s; 4s; 5s; 6s |], cat.FLAGS)
    let row = cat.Rows[1]
    Assert.Equal(1, row.Index)
    Assert.Equal(2, row.ID)
    Assert.Equal("beta", row.NAME)
    Assert.Equal(2.5f<Jy>, row.FLUX)
    Assert.Equal<float32[]>([| 4.f |], row.SPEC)
    Assert.Equal<int16[]>([| 4s; 5s; 6s |], row.FLAGS)
    Assert.Equal(None, row.OK)
    Assert.Equal(Some true, (cat.Row 0).OK)
    Assert.Equal(2, cat.Table.Rows)
    Assert.Equal(Some "CAT", cat.Info.Name)

[<Fact>]
let ``HDUs are found by EXTNAME rather than position`` () =
    use original = Fits.openFile Sample
    let swapped =
        Fits.toBytes [ Fits.copy original 0; Fits.copy original 2; Fits.copy original 1 ]
    use file = Obs.Parse swapped
    Assert.Equal(1, file.SCI.Info.Index)
    Assert.Equal(2, file.CAT.Info.Index)
    Assert.Equal("beta", file.CAT.Rows[1].NAME)

[<Fact>]
let ``a file missing a keyword fails when that keyword is read`` () =
    use original = Fits.openFile Sample

    let stripped = {
        Fits.copy original 0 with
            Header = Header.remove "FILTER" original.Primary.Header
    }

    use file = Obs.Parse(Fits.toBytes [ stripped ])
    Assert.Equal("M31", file.Primary.OBJECT)
    Assert.Throws<Collections.Generic.KeyNotFoundException>(fun () -> file.Primary.FILTER |> ignore)
    |> ignore

[<Fact>]
let ``Load accepts seekable and non-seekable streams`` () =
    use stream = File.OpenRead Sample
    use file = Obs.Load stream
    Assert.Equal("M31", file.Primary.OBJECT)
    use unseekable = new NonSeekableStream(File.ReadAllBytes Sample)
    use buffered = Obs.Load unseekable
    Assert.Equal<int[]>([| 1; 2 |], buffered.CAT.ID)

[<Fact>]
let ``GetSample opens the sample the type came from`` () =
    use file = Obs.GetSample()
    Assert.Equal("M31", file.Primary.OBJECT)
    Assert.Equal(3, file.File.Count)

[<Fact>]
let ``Load and AsyncLoad fetch URLs`` () =
    let url, server = serve (File.ReadAllBytes Sample)
    use server = server
    use file = Obs.AsyncLoad url |> Async.RunSynchronously
    Assert.Equal("M31", file.Primary.OBJECT)
    use again = Obs.Load url
    Assert.Equal("beta", again.CAT.Rows[1].NAME)

[<Fact>]
let ``AsyncLoad opens local paths too`` () =
    use file = Obs.AsyncLoad Sample |> Async.RunSynchronously
    Assert.Equal(0.5, file.Primary.ESO_DET_DIT)

